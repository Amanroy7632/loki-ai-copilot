//! Conversations and their messages.
//!
//! A [`Message`] is one stored turn of a conversation. It is the shape persisted by
//! `loki-memory`, shown in history, and (after context building) sent to a model provider.

use serde::{Deserialize, Serialize};

use crate::ids::{ConversationId, MessageId};
use crate::time::UnixMillis;

/// Who authored a message.
///
/// The set is closed on purpose: the `messages.role` column has a `CHECK` constraint with the
/// same four values, so storage and contracts can't drift apart silently.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(rename_all = "snake_case")]
pub enum Role {
    /// Instructions from Loki itself (the system prompt). Never written by the user or a tool.
    System,
    /// Text the user typed or said.
    User,
    /// Text produced by the model.
    Assistant,
    /// A tool result fed back to the model. Always treated as untrusted data.
    Tool,
}

impl Role {
    /// Every role, for exhaustive tests.
    pub const ALL: [Self; 4] = [Self::System, Self::User, Self::Assistant, Self::Tool];

    /// The stable lowercase name, identical to the serde form and the SQL `CHECK` values.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::System => "system",
            Self::User => "user",
            Self::Assistant => "assistant",
            Self::Tool => "tool",
        }
    }

    /// Parses the stable name. Returns `None` for anything else, so callers must handle
    /// corrupt or unexpected stored values explicitly instead of defaulting to a role.
    pub fn parse(value: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|role| role.as_str() == value)
    }
}

/// One message in a conversation.
///
/// Unknown fields are rejected, so data crossing the IPC boundary can't carry extra payloads.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(deny_unknown_fields)]
pub struct Message {
    /// Unique message ID (UUID v7 text, generated by the runtime).
    pub id: MessageId,
    /// The conversation this message belongs to.
    pub conversation_id: ConversationId,
    /// Who wrote it.
    pub role: Role,
    /// The text content.
    pub content: String,
    /// When it was stored, UTC.
    pub created_at: UnixMillis,
    /// `true` when generation was stopped by the user before the model finished (P2-T02).
    /// The content is then partial. Always `false` for non-assistant messages.
    pub stopped: bool,
}

impl Message {
    /// A complete (not stopped) message.
    pub fn new(
        id: MessageId,
        conversation_id: ConversationId,
        role: Role,
        content: impl Into<String>,
        created_at: UnixMillis,
    ) -> Self {
        Self {
            id,
            conversation_id,
            role,
            content: content.into(),
            created_at,
            stopped: false,
        }
    }
}

/// A conversation's summary, as listed in history. Messages are loaded separately.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(deny_unknown_fields)]
pub struct Conversation {
    /// Unique conversation ID (UUID v7 text, generated by the runtime).
    pub id: ConversationId,
    /// Display title. P1 derives it from the first user message; it is never sent to tools.
    pub title: String,
    /// When the conversation was created, UTC.
    pub created_at: UnixMillis,
    /// When a message was last added, UTC. History lists sort by this, newest first.
    pub updated_at: UnixMillis,
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn sample() -> Message {
        Message {
            id: MessageId::new("msg-1"),
            conversation_id: ConversationId::new("conv-1"),
            role: Role::Assistant,
            content: "Hello".into(),
            created_at: UnixMillis(1_800_000_000_000),
            stopped: true,
        }
    }

    #[test]
    fn stopped_is_required_on_the_wire() {
        let mut raw = serde_json::to_value(sample()).unwrap();
        assert_eq!(raw["stopped"], true);
        raw.as_object_mut().unwrap().remove("stopped");
        assert!(serde_json::from_value::<Message>(raw).is_err());
    }

    #[test]
    fn message_round_trips() {
        let message = sample();
        let encoded = serde_json::to_string(&message).unwrap();
        assert_eq!(serde_json::from_str::<Message>(&encoded).unwrap(), message);
    }

    #[test]
    fn conversation_round_trips_and_rejects_unknown_fields() {
        let conversation = Conversation {
            id: ConversationId::new("conv-1"),
            title: "Groceries".into(),
            created_at: UnixMillis(1),
            updated_at: UnixMillis(2),
        };
        let encoded = serde_json::to_string(&conversation).unwrap();
        assert_eq!(
            serde_json::from_str::<Conversation>(&encoded).unwrap(),
            conversation
        );
        let mut raw = serde_json::to_value(&conversation).unwrap();
        raw["owner"] = json!("someone");
        assert!(serde_json::from_value::<Conversation>(raw).is_err());
    }

    #[test]
    fn message_rejects_unknown_fields() {
        let mut raw = serde_json::to_value(sample()).unwrap();
        raw["approved"] = json!(true);
        assert!(serde_json::from_value::<Message>(raw).is_err());
    }

    #[test]
    fn role_serde_name_matches_as_str_and_parse() {
        for role in Role::ALL {
            assert_eq!(serde_json::to_value(role).unwrap(), role.as_str());
            assert_eq!(Role::parse(role.as_str()), Some(role));
            let encoded = serde_json::to_string(&role).unwrap();
            assert_eq!(serde_json::from_str::<Role>(&encoded).unwrap(), role);
        }
    }

    #[test]
    fn role_parse_rejects_unknown_and_differently_cased_values() {
        assert_eq!(Role::parse("admin"), None);
        assert_eq!(Role::parse("User"), None);
        assert_eq!(Role::parse(""), None);
        assert!(serde_json::from_str::<Role>("\"developer\"").is_err());
    }
}
